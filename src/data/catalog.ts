const material = (name: string, tags: string[]) => ({ name, tags, quantity: 1 });
const fetch = (ingredients: Record<string, number>): RecipeStep => ({
  id: 'fetch',
  label: '领取食材',
  method: 'Fetch',
  equipment: 'fridge',
  dependencies: [],
  activeTime: 6,
  passiveTime: 0,
  inputs: [],
  // Rice is debited once when the shared batch starts, then reserved by rice tasks.
  outputs: Object.entries(ingredients)
    .filter(([name]) => name !== 'rice')
    .map(([name, quantity]) => ({ name, quantity, tags: [...INGREDIENTS[name].tags] })),
});
const rice = (): RecipeStep => ({
  id: 'rice',
  label: '领取熟米饭 / 等待批次',
  method: 'CookRice',
  equipment: 'rice',
  dependencies: ['fetch'],
  activeTime: 3,
  passiveTime: 0,
  inputs: [],
  outputs: [material('rice', ['cooked'])],
});
const pass = (dish: string, dependency: string): RecipeStep => ({
  id: 'pass',
  label: '送至出餐台',
  method: 'Pass',
  equipment: 'serving',
  tool: 'plate',
  dependencies: [dependency],
  activeTime: 4,
  passiveTime: 0,
  inputs: [material(dish, ['cooked', 'ready'])],
  outputs: [material(dish, ['cooked', 'ready'])],
});
const ingredientCost = (ingredients: Record<string, number>) =>
  Object.entries(ingredients).reduce(
    (sum, [name, quantity]) => sum + INGREDIENTS[name].cost * quantity,
    0,
  );

