const perimeter = (width: number, height: number): Point[] => [
  ...Array.from({ length: width }, (_, x) => ({ x, y: -1 })),
  ...Array.from({ length: width }, (_, x) => ({ x, y: height })),
  ...Array.from({ length: height }, (_, y) => ({ x: -1, y })),
  ...Array.from({ length: height }, (_, y) => ({ x: width, y })),
];

const equipment = (
  kind: EquipmentKind,
  name: string,
  category: string,
  width: number,
  height: number,
  capacity: number,
  methods: EquipmentDefinition['methods'],
  tools: ToolKind[],
  purchaseCost: number,
  operatingCost = 0.015,
  powerConsumption = 0,
  processingDuration = 0,
  extra: Partial<EquipmentDefinition> = {},
): EquipmentDefinition => ({
  kind,
  name,
  category,
  width,
  height,
  capacity,
  methods,
  tools,
  purchaseCost,
  operatingCost,
  powerConsumption,
  processingDuration,
  interactionSlots: perimeter(width, height),
  ...extra,
});

